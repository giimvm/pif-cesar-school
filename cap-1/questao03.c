#include <stdio.h>

/*
    Programa: Soma de dois números
    Objetivo: Ler dois números inteiros,
    calcular a soma e exibir o resultado.
*/

int main(void) {

    // Declara as variáveis que armazenarão os números
    int num1 = 10;
    int num2 = 5;

    // Calcula a soma dos dois números
    int soma = num1 + num2;

    // Exibe o resultado da soma
    printf("A soma e: %d\n", soma);

    return 0;
}